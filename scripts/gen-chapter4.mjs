#!/usr/bin/env node
/** Extract Chapter 4 table rows → src/platform/longform/chapter4.ts */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SCRIPT_DIR = new URL('.', import.meta.url).pathname;
const ROOT = join(SCRIPT_DIR, '..');

const candidateMd = [
  join(ROOT, 'docs', 'mychef-hawaii-discovery_sec04.md'),
  join(ROOT, 'mychef-hawaii-discovery_sec04.md'),
  join(ROOT, '..', 'mychef-hawaii-discovery_sec04.md'),
];

const mdPath = candidateMd.find((p) => existsSync(p));
const targetPath = existsSync(join(ROOT, 'src', 'platform', 'longform'))
  ? join(ROOT, 'src', 'platform', 'longform', 'chapter4.ts')
  : join(ROOT, 'app', 'src', 'platform', 'longform', 'chapter4.ts');

if (!mdPath) {
  if (existsSync(targetPath)) {
    console.log('chapter4.ts: using existing generated file.');
    process.exit(0);
  }
  throw new Error('mychef-hawaii-discovery_sec04.md not found');
}

const ch4 = readFileSync(mdPath, 'utf8');

const SLICES = [
  ['oahu', '#### 4.2.1', '#### 4.2.2'],
  ['maui', '#### 4.2.2', '#### 4.2.3'],
  ['kauai', '#### 4.2.3', '#### 4.2.4'],
  ['bigisland', '#### 4.2.4', '### 4.3'],
  ['hub', '#### 4.3.1', '### 4.4'],
];

function slice(md, a, b) {
  const i = md.indexOf(a);
  const j = md.indexOf(b, i + 1);
  return i >= 0 ? md.slice(i, j > 0 ? j : undefined) : '';
}

function cleanKw(kw) {
  return kw
    .replace(/\s*\(EST\.[^)]*\)/gi, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function esc(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, ' ');
}

const rows = [];
for (const [site, a, b] of SLICES) {
  const block = slice(ch4, a, b);
  for (const line of block.split('\n')) {
    const m = line.match(/^\|\s*`(\/[^`]*)`\s*\|\s*([^|]+)\|\s*([^|]+)\|\s*([^|]*)\|\s*([^|]+)\|\s*(.*)\|\s*$/);
    if (!m) continue;
    const path = m[1].replace(/\/$/, '') || '/';
    const slug = path === '/' ? '' : path.slice(1);
    rows.push({
      key: `${site}:${slug}`,
      keyword: cleanKw(m[3]),
      category: m[2].trim(),
      notes: m[6].replace(/\[\^[^\]]+\]/g, '').replace(/\s+/g, ' ').trim(),
    });
  }
}

const body = `/* Generated by scripts/gen-chapter4.mjs from mychef-hawaii-discovery_sec04.md — do not edit by hand. */
export interface Ch4Brief {
  keyword: string;
  category: string;
  notes: string;
}

export const CHAPTER4: Record<string, Ch4Brief> = {
${rows
  .map((r) => `  '${esc(r.key)}': { keyword: '${esc(r.keyword)}', category: '${esc(r.category)}', notes: '${esc(r.notes)}' },`)
  .join('\n')}
};

export function briefOf(siteId: string, slug: string): Ch4Brief | undefined {
  return CHAPTER4[\`\${siteId}:\${slug}\`];
}
`;

writeFileSync(targetPath, body);
console.log(`chapter4.ts: ${rows.length} briefs`);
